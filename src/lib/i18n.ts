type Vars = Record<string, string | number>;

/** Tradução da chave para o idioma passado. */
export function tr(lang: Language, key: string, vars?: Vars): string {
  let s = MESSAGES[lang]?.[key] ?? MESSAGES.pt[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Tradução para o idioma atual do app (lida da store). */
export function t(key: string, vars?: Vars): string {
  return tr(useStore.getState().settings.lang, key, vars);
}

/** Hook que devolve a tradução para o idioma atual; re-renderiza ao mudar o idioma. */
export function useTr(): (key: string, vars?: Vars) => string {
  const lang = useStore((s) => s.settings.lang);
  return (key, vars) => tr(lang, key, vars);
}

export const langOf = (): Language => useStore.getState().settings.lang;

/** Código BCP-47 do idioma, para a fonte e o locale de data do sistema. */
export const langCode: Record<Language, string> = { pt: "pt-BR", en: "en-US", es: "es-ES", fr: "fr-FR", de: "de-DE", it: "it-IT" };
export const langCodeOf = (lang: Language): string => langCode[lang];

/** Código de duas letras do idioma (pt, en, es, fr, de, it) — para vozes do sistema e dc:language do EPUB. */
export const langPrefix = (lang: Language): string => langCodeOf(lang).split("-")[0].toLowerCase();
